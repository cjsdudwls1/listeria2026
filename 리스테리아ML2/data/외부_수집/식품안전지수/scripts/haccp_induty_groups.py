def our_pairs():
    p = (pd.read_parquet(SAMPLE, columns=['train_prdlst_code', 'train_prdlst_nm'])
         .dropna(subset=['train_prdlst_code']).drop_duplicates().sort_values('train_prdlst_code'))
    return p


def group_codes(pairs):
    """묶음 → [(code, nm), ...]"""
    allc = list(pairs.itertuples(index=False, name=None))
    food = [(c, n) for c, n in allc if c.startswith('C') and c not in LIVESTOCK_CODES]
    live = [(c, n) for c, n in allc if c in LIVESTOCK_CODES]
    add = [(c, n) for c, n in allc if c.startswith('D')]
    hff = [(c, n) for c, n in allc if c.startswith('E')]
    return {G_FOOD: food, G_LIVE: live, G_ADD: add, G_HFF: hff, G_INST: [], G_SERV: [], NONE: []}


def group_of(induty):
    if induty is None or (isinstance(induty, float) and pd.isna(induty)) or not str(induty).strip():
        return NONE, '업종 빈 값'
    s = str(induty)
    if s in INDUTY:
        return INDUTY[s]
    return NONE, '대응 규칙 목록에 없는 업종 — 확인 필요'
