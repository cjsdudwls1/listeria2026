def load_sgg(path):
    s = pd.read_parquet(path)[['sgg_code', 'sgg_nm']].copy()
    s['sgg_code'] = s['sgg_code'].astype(str)
    return s


def build_lookup(sgg):
    """이름 → 코드 목록. '경기도 수원시' 같은 시 이름은 그 시의 구 전부."""
    full = dict(zip(sgg['sgg_nm'], sgg['sgg_code']))
    return full


def map_name(sido, name, year, sgg):
    """자료 쪽 (시도 줄임말, 시군구 이름, 자료연도) → dict(codes, 유형, 이름바뀜, 나뉨, 합쳐짐, 시단위값, 설명).
    year 는 자료연도(지하수는 판-1). 대응 못 하면 codes=[]"""
    nm = str(name).strip()
    sd = str(sido).strip()
    res = {'codes': [], '유형': '', '이름바뀜': False, '나뉨': False, '합쳐짐': False, '시단위값': False, '설명': ''}
    notes = []
    if sd in SIDO_RENAMED:
        res['이름바뀜'] = True
        notes.append('시도: ' + SIDO_RENAMED[sd])
    full_sido = SIDO_FULL.get(sd)
    nm_ns = nm.replace(' ', '')
    byname = dict(zip(sgg['sgg_nm'], sgg['sgg_code']))

    def setr(codes, typ, note=None):
        res['codes'] = list(codes)
        res['유형'] = typ
        if note:
            notes.append(note)

    # ---- 개별 규칙 ----
    if sd == '세종':
        setr(['36110'], '그대로', f"'{nm}' = 세종특별자치시")
    elif sd == '인천' and nm == '남구':
        res['이름바뀜'] = True
        setr(['28177'], '이름바뀜', '인천 남구 → 미추홀구(2018-07-01)')
    elif sd == '인천' and nm == '중구':
        res['나뉨'] = True; res['합쳐짐'] = True
        setr(['28125', '28155'], '나뉨+합쳐짐',
             '인천 중구 → 제물포구(내륙, 옛 동구와 합침)·영종구(영종·용유)로 나뉨(2026-07-01 개편)')
    elif sd == '인천' and nm == '동구':
        res['합쳐짐'] = True
        setr(['28125'], '합쳐짐', '인천 동구 → 옛 중구 내륙과 합쳐 제물포구(2026-07-01 개편)')
    elif sd == '인천' and nm == '서구':
        res['나뉨'] = True
        setr(['28275', '28290'], '나뉨', '인천 서구 → 서해구·검단구로 나뉨(2026-07-01 개편)')
    elif sd == '인천' and nm_ns in ('중구영종출장', '중구용유출장'):
        res['이름바뀜'] = True
        setr(['28155'], '출장소', f"'{nm}'(옛 인천 중구 출장소) → 영종구")
    elif sd == '인천' and nm_ns == '서구검단출장':
        res['이름바뀜'] = True
        setr(['28290'], '출장소', "'서구검단출장'(옛 인천 서구 출장소) → 검단구")
    elif nm == '군위군' and sd in ('경북', '대구'):
        if sd == '경북':
            res['이름바뀜'] = True
            setr(['27720'], '시도 바뀜', '경상북도 군위군 → 대구광역시 군위군(2023-07-01 편입)')
        else:
            setr(['27720'], '그대로', '대구광역시 군위군')
    elif sd == '경기' and nm == '여주군':
        res['이름바뀜'] = True
        setr(['41670'], '이름바뀜', '여주군 → 여주시(2013-09-23 시 승격)')
    elif sd == '충북' and nm == '청원군':
        res['합쳐짐'] = True; res['나뉨'] = True
        setr(['43111', '43112', '43113', '43114'], '합쳐짐+나뉨',
             '청원군 → 옛 청주시와 합쳐 오늘 청주시 4개 구로 나뉨(2014-07-01 통합)')
    elif sd == '충북' and nm == '청주시' and year <= 2014:
        res['합쳐짐'] = True; res['시단위값'] = True
        setr(['43111', '43112', '43113', '43114'], '합쳐짐+시단위',
             '통합 전 청주시(청원군 별도) → 오늘 청주시 4개 구(2014-07-01 통합)')
    elif sd == '경남' and nm_ns == '사천남양출장':
        res['이름바뀜'] = True
        setr(['48240'], '출장소', "'사천남양출장'(사천시 출장소) → 사천시")
    elif sd == '전북' and nm_ns == '익산시함열출':
        res['이름바뀜'] = True
        setr(['52140'], '출장소', "'익산시함열출'(익산시 출장소) → 익산시")
    elif sd == '전북' and nm_ns == '전주시효자출':
        res['이름바뀜'] = True; res['시단위값'] = True
        setr(['52111', '52113'], '출장소', "'전주시효자출'(전주시 출장소, 구 표시 없음) → 전주시 두 구(시 단위)")
    elif sd == '경기' and nm == '부천시':
        res['나뉨'] = True; res['시단위값'] = True
        setr(['41192', '41194', '41196'], '시단위(구 신설)',
             '부천시 → 원미구·소사구·오정구(2024-01-01 일반구 설치, 2016-07~2023 구 없음)')
    elif sd == '경기' and nm == '화성시':
        res['나뉨'] = True; res['시단위값'] = True
        setr(['41591', '41593', '41595', '41597'], '시단위(구 신설)',
             '화성시 → 만세구·효행구·병점구·동탄구(우리 목록의 일반구 4개)')
    else:
        if full_sido is None:
            setr([], '대응 못 함', f'시도 줄임말 {sd} 모름')
        else:
            key = f'{full_sido} {nm}'
            if key in byname:
                setr([byname[key]], '그대로' if not res['이름바뀜'] else '시도 이름·코드 바뀜')
            else:
                # 일반시 → 구 여러 개
                pref = key + ' '
                cs = sgg.loc[sgg['sgg_nm'].str.startswith(pref), 'sgg_code'].tolist()
                if cs:
                    res['시단위값'] = True
                    setr(cs, '시단위(일반구)', f'{nm} 은 시 단위 자료 → 그 시의 구 {len(cs)}개에 같은 값')
                else:
                    setr([], '대응 못 함', f'우리 목록에 {key} 없음')
    res['설명'] = '; '.join(notes)
    return res


