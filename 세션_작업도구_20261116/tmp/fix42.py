def rep(old, new, n=1):
    global t
    c = t.count(old)
    assert c == n, (c, old)
    t = t.replace(old, new)
    log.append(old[:40])


def line_replace(prefix, new):
    """replace the single whole line starting with prefix (new=None -> delete)"""
    global t
    L = t.split('\n')
    idx = [i for i, l in enumerate(L) if l.startswith(prefix)]
    assert len(idx) == 1, (len(idx), prefix)
    if new is None:
        del L[idx[0]]
    else:
        L[idx[0]] = new
    t = '\n'.join(L)
    log.append('LINE ' + prefix[:40])


def insert_after(prefix, new_lines):
    global t
    L = t.split('\n')
    idx = [i for i, l in enumerate(L) if l.startswith(prefix)]
    assert len(idx) == 1, (len(idx), prefix)
    L[idx[0] + 1:idx[0] + 1] = new_lines
    t = '\n'.join(L)
    log.append('INS ' + prefix[:40])


def insert_before(prefix, new_lines):
    global t
    L = t.split('\n')
    idx = [i for i, l in enumerate(L) if l.startswith(prefix)]
    assert len(idx) == 1, (len(idx), prefix)
    L[idx[0]:idx[0]] = new_lines
    t = '\n'.join(L)
    log.append('INSB ' + prefix[:40])


