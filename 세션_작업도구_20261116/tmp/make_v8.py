def rep(old, new, cnt=1):
    global t
    c = t.count(old)
    if c != cnt:
        sys.exit(f'COUNT {c} != {cnt}: {old[:60]}')
    t = t.replace(old, new)


def take_line(prefix):
    """remove the whole line starting with prefix, return its text (no newline)"""
    global t
    L = t.split('\n')
    idx = [i for i, l in enumerate(L) if l.startswith(prefix)]
    if len(idx) != 1:
        sys.exit(f'LINE {len(idx)}: {prefix}')
    s = L.pop(idx[0])
    t = '\n'.join(L)
    return s


