def rep(old, new, cnt=1):
    global t
    c = t.count(old)
    if c != cnt:
        sys.exit(f'COUNT {c} != {cnt}: {old[:80]}')
    t = t.replace(old, new)


def line_replace(prefix, new):
    global t
    L = t.split('\n')
    idx = [i for i, l in enumerate(L) if l.startswith(prefix)]
    if len(idx) != 1:
        sys.exit(f'LINE {len(idx)}: {prefix}')
    L[idx[0]] = new
    t = '\n'.join(L)


