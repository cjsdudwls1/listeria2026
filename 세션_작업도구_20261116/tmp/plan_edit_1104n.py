def rep(old, new, cnt=1):
    global t
    n = t.count(old)
    assert n == cnt, (n, old[:90])
    t = t.replace(old, new)


def repline(prefix, newline):
    global t
    lines = t.split('\n')
    idx = [i for i, l in enumerate(lines) if l.startswith(prefix)]
    assert len(idx) == 1, (len(idx), prefix[:60])
    lines[idx[0]] = newline
    t = '\n'.join(lines)


def repblock(start, end_incl, new):
    global t
    assert t.count(start) == 1, start[:60]
    i = t.index(start)
    j = t.index(end_incl, i) + len(end_incl)
    t = t[:i] + new + t[j:]


